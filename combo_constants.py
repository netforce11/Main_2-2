def mk_item(text, color=None):
    """공통 테이블 아이템 생성."""
    it = QTableWidgetItem(str(text))
    it.setTextAlignment(Qt.AlignCenter)
    if color:
        it.setForeground(QBrush(QColor(color)))
    return it